import SwiftUI

/// 개인정보 처리방침 — 앱 내 화면.
///
/// "키보드로 입력한 내용은 수집·전송하지 않는다"는 `.claude/rules/security.md`의 1순위 규칙이며,
/// **코드가 이 문서와 어긋나면 코드가 아니라 규칙 위반이다.** 설정 앱의 이용 분석(Firebase Analytics)·
/// 오류 진단(Firebase Crashlytics)은 키보드 익스텐션과 무관하며 이 문서 하단 절에서 별도로 고지한다.
/// App Store Connect에는 같은 내용의 웹 URL 게시가 별도로 필요하다 — `docs/release/privacy-policy-web.md`.
///
/// **대략적 위치·보유 기간·수탁자·웹 처리방침 링크는 빼지 않는다** (반론자 B-1·B-2, 2026-09-14).
/// Coarse Location 을 매니페스트에 선언해 놓고 처리방침이 위치를 한 글자도 말하지 않으면
/// 스토어 라벨과 고지가 어긋난다. 보유·파기와 수탁자 동등보호, 그리고 게시된 전문으로 가는 링크는
/// 심사 가이드라인 5.1.1(i)이 요구하는 요소다. **문안은 사장님이 정한 정본이다** — 웹 처리방침
/// (https://geulsoe-keyboard.web.app/privacy)과 같은 문장을 써야 앱과 웹이 갈라지지 않는다.
///
/// **2026-09-14 — 보유·파기와 수탁자 문구를 라이브 웹 4장 표현으로 되맞췄다** (디자이너 지적).
/// 앱 쪽이 요약되면서 (가) 보존 기간의 유보("실제 설정값은 아직 콘솔에서 확인하지 않았다")와
/// (나) 수탁자 판단의 근거("Firebase 데이터 처리 약관 및 Google 개인정보처리방침 기준")가 빠져
/// **앱이 웹보다 강하게 단정**하고 있었다. 새 문장을 지어 넣은 것이 아니라 게시본에서 그대로 가져왔다 —
/// 두 문서가 같은 강도를 갖는 것이 이 화면의 목적이다.
///
/// **분석 절은 반드시 끄는 경로를 함께 보여준다** — 심사 가이드라인 5.1.1(ii)가 요구하는
/// "접근 가능하고 이해하기 쉬운 동의 철회 수단"이며, 안내만 있고 경로가 없으면 그 문장이 심사에서
/// 불리한 자백이 된다 (v1.0.0 상태). 링크 대상은 `AnalyticsSettingsView`.
struct PrivacyPolicyView: View {

    var body: some View {
        List {
            Section("키보드가 입력 내용을 다루는 방식") {
                policyItem(
                    "입력 내용",
                    "키보드로 입력한 모든 내용은 수집·저장·전송되지 않습니다. 키보드 익스텐션에는 네트워크 기능이 없습니다."
                )
                policyItem(
                    "계정·광고",
                    "계정을 만들지 않고, 광고 식별자를 읽지 않으며, 광고를 위한 추적을 하지 않습니다."
                )
            }

            Section("설정 앱의 이용 분석·오류 진단") {
                policyItem(
                    "무엇이 나가나요",
                    "설정 앱(이 화면들)을 사용하는 동안의 일반적인 사용 패턴(화면 조회, 기능 사용 여부)과 오류가 발생했을 때의 진단 정보(크래시 발생 지점, 기기 모델, OS 버전)가 개발사와 개발사가 이용하는 처리업체(Google)에 전달됩니다."
                )
                policyItem(
                    "키보드는 포함되지 않습니다",
                    "이 분석·진단 기능은 설정 앱에만 있으며, 키보드 익스텐션 코드에는 포함되어 있지 않습니다. 입력하신 텍스트, 클립보드 내용, 학습 단어, 채움글 내용은 이 분석에 절대 포함되지 않습니다."
                )
                policyItem(
                    "대략적 위치",
                    "수집 항목에 대략적 위치(국가·지역)가 포함됩니다. 접속 IP에서 도출되는 값이며, 정확한 위치가 아닙니다. 글쇠는 위치 권한을 요구하지 않고 위경도를 받지 않습니다."
                )
                policyItem(
                    "언제든 끌 수 있습니다",
                    "아래 '이용 분석·오류 진단'에서 이용 분석과 오류 진단을 각각 끌 수 있습니다. 정보 탭에서도 같은 화면으로 들어갈 수 있습니다."
                )
                NavigationLink("이용 분석·오류 진단") { AnalyticsSettingsView() }
            }

            Section("기기 안에만 저장되는 것") {
                policyItem(
                    "키보드 설정",
                    "자판·테마 등 설정은 이 기기의 앱 전용 저장 공간(App Group)에만 저장됩니다."
                )
                // ★ 「내 문구 (채움글)」 → **「내 채움글」** (사용자 지시 2026-09-23).
                //
                // 이 절의 제목은 **「항목 (그 항목이 속한 기능)」** 꼴이다 —
                // 「학습 단어 (추천단어)」처럼 **항목 이름과 기능 이름이 다를 때** 괄호가 일한다.
                // 이제 항목 이름이 「내 채움글」이라 기능 이름을 **이미 품고 있다** —
                // 「내 채움글 (채움글)」은 같은 말의 되풀이다.
                //
                // ★ **뜻은 달라지지 않는다**(처리방침은 심사에서 본 문서라 확인했다):
                //   밝히는 대상이 *직접 추가한 단축어와 본문*으로 **그대로**이고,
                //   기능으로 가는 길(「설정 > 채움글에서 삭제할 수 있습니다」)도 **본문에 그대로 있다.**
                //   바뀐 것은 **부르는 이름 하나뿐**이고, 그 이름은 화면과 일치해야 사용자가 찾는다.
                policyItem(
                    "내 채움글",
                    "직접 추가한 단축어와 본문은 기기 안에만 저장되며, 설정 > 채움글에서 삭제할 수 있습니다."
                )
                policyItem(
                    "학습 단어 (추천단어)",
                    "자주 쓰는 단어의 사용 횟수만 기기 안에 저장됩니다. 비밀번호 입력란에서는 학습하지 않으며, 설정의 '학습 단어 초기화'로 모두 삭제할 수 있습니다."
                )
                policyItem(
                    "클립보드 기록",
                    "클립보드 기록이 켜져 있고 전체 접근이 허용된 경우, 키보드가 열릴 때와 툴바의 클립보드 도구를 열 때 읽은 클립보드 내용(최근 30개, 항목당 2,000자까지)을 기기 안에만 저장합니다. 비밀번호 입력란에서는 기록하지 않습니다. 항목별 삭제·모두 지우기가 가능하고, 설정에서 기록을 끄면 저장된 기록이 즉시 삭제됩니다."
                )
            }

            Section("전체 접근 허용") {
                policyItem(
                    "켜지 않아도 됩니다",
                    "한글 입력·채움글·추천단어 등 핵심 기능은 전체 접근 없이 동작합니다. 전체 접근에 의존하는 것은 네 가지입니다: 학습한 단어의 영구 저장(없으면 키보드가 열려 있는 동안만 유지), 복사한 인증번호 제안, 클립보드 도구와 기록, 그리고 키 입력 진동."
                )
                policyItem(
                    "클립보드",
                    "클립보드는 주기적으로 감시하지 않습니다. 읽는 시점은 키보드가 열릴 때 1회(인증번호 제안 또는 클립보드 기록이 켜진 경우)와 클립보드 도구를 열 때뿐입니다. 인증번호 제안은 클립보드에서 찾은 번호를 툴바에 표시하며, 찾은 번호는 툴바 표시와 입력란 삽입 외에 저장·전송되지 않습니다 (클립보드 기록이 켜져 있으면 복사한 원문은 위 '클립보드 기록'에 남습니다). 두 기능은 각각 설정에서 끌 수 있습니다."
                )
            }

            Section("보관 기간과 처리 위탁") {
                policyItem(
                    "보유·파기",
                    "오류 보고서는 90일 안에 삭제됩니다. 이용 분석 데이터의 실제 보존 설정은 아직 확인 전이라, 더 긴 쪽인 최대 14개월을 상한으로 고지합니다."
                )
                policyItem(
                    "수탁자",
                    "Google LLC 가 이 처리방침과 동등한 수준의 보호를 제공함을 확인했습니다 (Firebase 데이터 처리 약관 및 Google 개인정보처리방침 기준)."
                )
            }

            Section {
                Text("앱을 삭제하면 위의 모든 데이터가 함께 삭제됩니다.")
                    .font(.footnote)
                    .foregroundStyle(.secondary)
                Link("전체 처리방침 보기",
                     destination: URL(string: "https://geulsoe-keyboard.web.app/privacy")!)
                    .font(.footnote)
            }
        }
        .settingsFormWidth()
        .navigationTitle("개인정보 처리방침")
        .navigationBarTitleDisplayMode(.inline)
    }

    private func policyItem(_ heading: String, _ body: String) -> some View {
        VStack(alignment: .leading, spacing: 5) {
            Text(heading)
                .font(.headline)
            Text(body)
                .font(.footnote)
                .foregroundStyle(.secondary)
        }
        .padding(.vertical, 2)
    }
}
